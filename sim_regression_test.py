async def main():
    bad = 0
    for i, (name, turns) in enumerate(CASES):
        p = store.create(f"90000001{i:02d}", actor="test")
        st = {"pid": p["id"], "mode": "chat"}
        brain.opening(st)
        print(f"\n=== {name}")
        for line, want, never in turns:
            out = await brain.respond(line, st)
            text = out["text"]
            ok = (not want or any(w in text for w in want)) and not any(w in text for w in never)
            bad += not ok
            print(f"{'OK ' if ok else 'BAD'} > {line[:70]}\n      {out['route']}\n      {text[:230]!r}")
    print(f"\n{'ALL PASSED' if not bad else f'{bad} BAD'}")
    sys.exit(1 if bad else 0)

asyncio.run(main())
